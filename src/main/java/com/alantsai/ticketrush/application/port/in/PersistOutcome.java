package com.alantsai.ticketrush.application.port.in;

/**
 * 落庫的結果。
 *
 * <p><b>兩者都不得觸發回補。</b> 這是本列舉存在的理由 —— 若只回布林值「成功與否」,
 * 「重複」很容易被歸類成失敗,而失敗會回補庫存。**那筆庫存其實已經賣出去了,
 * 回補它就是超賣。**
 */
public enum PersistOutcome {

    /** 訂單已寫入資料庫。 */
    PERSISTED,

    /**
     * 相同冪等鍵的訂單已存在 —— 訊息被重送過。
     *
     * <p>成因是「回補或落庫成功、但 ack 之前崩潰」這個無法消除的窗口:
     * 訊息留在 pending 被重新領取,於是同一筆預扣被處理第二次。
     *
     * <p><b>這不是錯誤,是設計預期的路徑。</b> 它出現的次數是本層的量測項目之一 ——
     * 大於 0 代表崩潰窗口真的發生過,而冪等鍵確實擋住了它。
     */
    DUPLICATE,

    /**
     * 落庫失敗,已回補快取的預扣。
     *
     * <p>**這是「處理完畢」而非「未處理」** —— 那筆庫存已經還回去了,訊息可以 ack。
     * 不 ack 的話它會留在 pending,而 pending 非空會讓對帳停止回補
     * (那是刻意的保守),於是差額卡在那裡不動。
     *
     * <p>回補次數是本層的量測項目:它是「非同步落庫的失敗成本」的直接證據。
     */
    COMPENSATED
}
