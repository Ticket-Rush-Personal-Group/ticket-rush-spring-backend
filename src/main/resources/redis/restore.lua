-- 預扣的回補:把庫存加回去、把已購數減回去。
--
-- KEYS[1] = 庫存             KEYS[2] = 該使用者在該場次的已購數
-- ARGV[1] = 要回補的張數
--
-- 回傳: 回補後的庫存餘量
--
-- **兩個 key 必須一起改,因此仍是 Lua 而不是兩次呼叫。** 分兩次做的話,
-- 中間有一段時間「庫存已加回、已購數還沒減」—— 那個瞬間該使用者的限購額度被錯誤地佔用著,
-- 而他可能正好在重試。這種不一致不會報錯,只會讓某些使用者莫名其妙買不到票。
--
-- 已購數不設下限保護:回補只在確定曾經扣過的情況下呼叫,
-- 若出現負值代表回補次數多於扣減次數,那是必須被發現的錯誤,不該被 max(0, x) 靜默吸收。

redis.call('INCRBY', KEYS[1], ARGV[1])
redis.call('DECRBY', KEYS[2], ARGV[1])
return tonumber(redis.call('GET', KEYS[1]))
